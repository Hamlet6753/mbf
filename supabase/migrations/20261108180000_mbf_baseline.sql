CREATE VIEW "public"."genres_with_subgenres" WITH (security_invoker=true) AS
SELECT g.id AS genre_id,
    g.name AS genre_name,
    json_agg(json_build_object('id', s.id, 'name', s.name)) AS subgenres
   FROM genres g
     LEFT JOIN subgenres s ON s.genre_id = g.id
  GROUP BY g.id, g.name
  ORDER BY g.name;

