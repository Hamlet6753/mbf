CREATE OR REPLACE FUNCTION public.search_musicians(p_query text DEFAULT NULL::text, p_place_id bigint DEFAULT NULL::bigint, p_genre_ids bigint[] DEFAULT NULL::bigint[], p_subgenre_ids bigint[] DEFAULT NULL::bigint[], p_instrument_ids bigint[] DEFAULT NULL::bigint[], p_role_ids bigint[] DEFAULT NULL::bigint[], p_available boolean DEFAULT NULL::boolean, p_in_search boolean DEFAULT NULL::boolean, p_after_id bigint DEFAULT NULL::bigint, p_limit integer DEFAULT 20)
 RETURNS SETOF public_musicians
 LANGUAGE sql
 STABLE
 SET search_path TO ''
AS $function$
 select m.* from public.public_musicians m
 where (nullif(btrim(p_query),'') is null or concat_ws(' ',m.firstname,m.lastname,m.username) ilike '%'||left(p_query,200)||'%')
 and (p_place_id is null or m.place_id=p_place_id)
 and (p_available is null or m.available=p_available)
 and (p_in_search is null or m.in_search=p_in_search)
 and (p_after_id is null or m.id>p_after_id)
 and (coalesce(cardinality(p_genre_ids),0)=0 or exists(select 1 from public.public_musician_genres r where r.musician_id=m.id and r.genre_id=any(p_genre_ids)))
 and (coalesce(cardinality(p_subgenre_ids),0)=0 or exists(select 1 from public.public_musician_subgenres r where r.musician_id=m.id and r.subgenre_id=any(p_subgenre_ids)))
 and (coalesce(cardinality(p_instrument_ids),0)=0 or exists(select 1 from public.public_musician_instruments r where r.musician_id=m.id and r.instrument_id=any(p_instrument_ids)))
 and (coalesce(cardinality(p_role_ids),0)=0 or exists(select 1 from public.public_musician_roles r where r.musician_id=m.id and r.role_id=any(p_role_ids)))
 order by m.id limit greatest(1,least(coalesce(p_limit,20),100));
$function$;

