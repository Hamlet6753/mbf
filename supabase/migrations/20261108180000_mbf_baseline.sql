CREATE OR REPLACE FUNCTION public.remove_band_member(p_band_id bigint, p_musician_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_actor text;v_target text;
begin
 if auth.uid() is null then raise exception 'Authentication required' using errcode='42501'; end if;
 perform 1 from public.bands where id=p_band_id for update;
 select bm.member_role into v_actor from public.band_members bm join public.musicians m on m.id=bm.musician_id where bm.band_id=p_band_id and m.user_id=auth.uid();
