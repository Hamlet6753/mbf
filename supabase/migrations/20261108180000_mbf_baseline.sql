CREATE OR REPLACE FUNCTION public.add_band_member(p_band_id bigint, p_musician_id bigint, p_member_role text DEFAULT 'member'::text, p_role_id bigint DEFAULT NULL::bigint, p_custom_label text DEFAULT NULL::text)
 RETURNS band_members
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare v_actor_role text; v_target_role text; v_new public.band_members; v_role text:=coalesce(p_member_role,'member');
begin
 if auth.uid() is null then raise exception 'Authentication required' using errcode='42501'; end if;
 perform 1 from public.bands where id=p_band_id for update;
 if not found then raise exception 'Band not found' using errcode='P0002'; end if;
 select bm.member_role into v_actor_role from public.band_members bm join public.musicians m on m.id=bm.musician_id where bm.band_id=p_band_id and m.user_id=auth.uid();
 if v_actor_role is null or v_actor_role not in ('owner','admin') then raise exception 'Only owner or admin may manage members' using errcode='42501'; end if;
 if v_role not in ('owner','admin','member') then raise exception 'Invalid member role' using errcode='22023'; end if;
 select member_role into v_target_role from public.band_members where band_id=p_band_id and musician_id=p_musician_id;
 if v_actor_role='admin' and (v_role<>'member' or coalesce(v_target_role,'member')<>'member') then raise exception 'Only owners may manage privileged roles' using errcode='42501'; end if;
 if v_target_role='owner' and v_role<>'owner' and (select count(*) from public.band_members where band_id=p_band_id and member_role='owner')<=1 then raise exception 'Cannot demote the last owner'; end if;
 insert into public.band_members(band_id,musician_id,member_role,role_id,custom_label) values(p_band_id,p_musician_id,v_role,p_role_id,p_custom_label)
 on conflict(band_id,musician_id) do update set member_role=excluded.member_role,role_id=excluded.role_id,custom_label=excluded.custom_label returning * into v_new;
 return v_new;
end $function$;

